export const L5_INTENTS = ['Informational', 'Navigational', 'Commercial', 'Transactional', 'Local', 'Purchase', 'Evaluational', 'Compliance'];
export const L5_TYPES = ['Discovery', 'Research', 'Comparison', 'Evaluation', 'Recommendation', 'Problem-Solution', 'Purchase', 'Local', 'Compliance'];
export const L5_DEMANDS = ['High', 'Medium-High', 'Medium', 'Low'];
export const L5_PER_PLATFORM = 10;
const STALE_RUN_MS = 10 * 60 * 1000;
const dateInTz = (d: Date): string => new Intl.DateTimeFormat('en-CA', { timeZone: process.env.APP_TIMEZONE || 'Asia/Kolkata' }).format(new Date(d));
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

const list = (v: unknown): string[] =>
  Array.isArray(v) ? v.map((x) => String(x).trim()).filter(Boolean) : typeof v === 'string' && v.trim() ? v.split(/\r?\n|,/).map((x) => x.trim()).filter(Boolean) : [];
const str = (v: unknown): string => (typeof v === 'string' ? v.trim() : '');
const norm = (s: string): string => s.toLowerCase().replace(/[^a-z0-9ऀ-ॿ ]+/g, ' ').replace(/\s+/g, ' ').trim();
const pick = (value: string, allowed: string[]): string | null => allowed.find((a) => a.toLowerCase() === value.trim().toLowerCase()) ?? null;

// Port of the plugin's Layer 5 Master Prompt (KP21_Layers::layer5_prompt, v8.9.280). The business input is the profile only:
// the prompt tells the platform to research independently and NOT to use the keywords from any previous research layer.
export function layer5Prompt(c: Customer, platformKey: string): string {
  const p = (c.profile || {}) as Record<string, any>;
  const def = AI_PLATFORMS.find((x) => x.key === platformKey);
  const search = platformKey === 'google_ai'
    ? 'Search using Google AI Mode / live Google results for this Layer only.'
    : `Search on your ${def?.label || platformKey} platform only. Do not use another AI platform or external search engine.`;
  const block = (label: string, v: string) => `${label}:\n${v}\n\n`;
  return (
    'You are an AI Search Prompt Research expert.\n\n' +
    'Analyze the following Industry, Sector, Products/Services and Business Information to identify the natural prompts and queries that prospective customers are likely to use when searching for, researching, evaluating, comparing or purchasing these products, services and solutions ON YOUR PLATFORM ONLY.\n\n' +
    search +
    '\n\nBUSINESS INPUT\n\n' +
    block('Industry', str(p.industry)) +
    block('Sector', str(p.sector)) +
    block('Products / Services', list(p.products_services).join('\n')) +
    block('Product / Service Description', str(p.product_description) || str(p.product_short_description) || str(p.company_profile)) +
    block('Target Customer Segments', list(p.target_customer_segments ?? p.target_customer_segment).join('\n')) +
    block('Areas Served', list(p.areas_served).join('\n') || str(p.service_area)) +
    block('Target Location', list(p.locations).join('\n')).replace(/\n\n$/, '') +
    '\n\nTASK\n\nResearch exactly 10 highly relevant AI Search Prompts for this business.\n\n' +
    'The prompts should represent realistic and natural prompts that prospective customers are likely to use ON YOUR PLATFORM when discovering, researching, evaluating, comparing or purchasing the products, services, solutions or expertise described in the Business Input.\n\n' +
    'Research independently from the Business Input. Do not use keywords or outputs generated by any previous research layer.\n\n' +
    'The 10 prompts should include a balanced combination, where relevant, of Product/service discovery, Informational research, Commercial investigation, Product/service comparison, Evaluation, Recommendation, Problem/solution research, Transactional/buyer intent, Purchase intent, Local/location-based research, and Compliance or industry-specific research.\n\n' +
    'PROMPT QUALITY RULES\nPrompts must sound like natural questions or instructions that a real user would enter into an AI platform. Do not simply convert product names into questions. Do not generate artificial keyword-stuffed prompts. Do not create duplicate or near-duplicate prompts. Do not force every category if it is not relevant to the business. Keep every prompt strongly relevant to the supplied Business Input.\n\n' +
    `INTENT\nUse exactly one: ${L5_INTENTS.join(', ')}.\n\n` +
    `PROMPT TYPE\nUse exactly one: ${L5_TYPES.join(', ')}.\n\n` +
    `DEMAND\nEstimate the relative likelihood/opportunity of the prompt being used ON YOUR PLATFORM. Use exactly one: ${L5_DEMANDS.join(', ')}.\n\n` +
    'RANKING\nRank the 10 prompts from the highest business/search opportunity to the lowest. Rank must be exactly 1 through 10.\n\n' +
    'RETURN\nReturn exactly 10 records. For every record return exactly Rank, Prompt, Intent, Prompt Type, Demand. Return ONLY a valid JSON array using exactly these keys: rank, prompt, intent, prompt_type, demand. Do not return Primary Intent, Secondary Intent, Customer Journey, Reason, Search Volume, Keyword Difficulty, CPC, Explanations, Notes or any additional field. Do not include markdown, a heading, or commentary before or after the JSON.'
  );
}

export interface PromptRow { prompt: string; intent: string; promptType: string; demand: string }

// Reads the JSON array out of a model reply and keeps only valid, de-duplicated rows (max 10), same rules as the plugin's validator.
export function parseLayer5Reply(text: string): PromptRow[] {
  const s = text.indexOf('[');
  const e = text.lastIndexOf(']');
  if (s < 0 || e <= s) return [];
  let arr: any;
  try { arr = JSON.parse(text.slice(s, e + 1)); } catch { return []; }
  if (!Array.isArray(arr)) return [];
  const rows = arr
    .map((x: any, i: number) => ({ rank: Number(x?.rank) || i + 1, prompt: str(x?.prompt), intent: pick(str(x?.intent), L5_INTENTS), promptType: pick(str(x?.prompt_type ?? x?.promptType), L5_TYPES), demand: pick(str(x?.demand), L5_DEMANDS) }))
    .filter((x) => x.prompt && x.intent && x.promptType && x.demand && x.rank >= 1 && x.rank <= 10)
    .sort((a, b) => a.rank - b.rank);
  const seenRank = new Set<number>();
  const seen = new Set<string>();
  const out: PromptRow[] = [];
  for (const r of rows) {
    const n = norm(r.prompt);
    if (!n || seen.has(n) || seenRank.has(r.rank)) continue;
    seen.add(n);
    seenRank.add(r.rank);
    out.push({ prompt: r.prompt.slice(0, 600), intent: r.intent as string, promptType: r.promptType as string, demand: r.demand as string });
    if (out.length >= L5_PER_PLATFORM) break;
  }
  return out;
}

// Manual entry: one per line, "prompt | Intent | Prompt Type | Demand" (all but the prompt optional).
export function parseManualLines(text: string): PromptRow[] {
  const seen = new Set<string>();
  const out: PromptRow[] = [];
  for (const raw of text.split(/\r?\n/)) {
    const parts = raw.split(/\t|\|/).map((x) => x.trim());
    if (!parts[0]) continue;
    const n = norm(parts[0]);
    if (!n || seen.has(n)) continue;
    seen.add(n);
    out.push({ prompt: parts[0].slice(0, 600), intent: pick(parts[1] || '', L5_INTENTS) || 'Informational', promptType: pick(parts[2] || '', L5_TYPES) || 'Research', demand: pick(parts[3] || '', L5_DEMANDS) || 'Medium' });
    if (out.length >= L5_PER_PLATFORM) break;
  }
  return out;
}

@Injectable()
export class Layer5Service {
  private readonly log = new Logger('Layer5');
  private readonly lastCall = new Map<string, number>();

  constructor(
    @InjectRepository(Layer5Prompt) private readonly pr: Repository<Layer5Prompt>,
    @InjectRepository(Layer5Platform) private readonly pf: Repository<Layer5Platform>,
    @InjectRepository(Project) private readonly projects: Repository<Project>,
    @InjectRepository(Customer) private readonly customers: Repository<Customer>,
    private readonly globalApis: GlobalApisService,
    private readonly layers: LayersService,
  ) {}

  async monthOf(customerId: string, month: string): Promise<Project> {
    const idx = parseInt(String(month || '').replace(/^m/i, ''), 10);
    if (isNaN(idx)) throw new BadRequestException('month is required, e.g. M3.');
    const p = await this.projects.findOne({ where: { customerId, monthIndex: idx } });
    if (!p) throw new NotFoundException(`Month M${idx} does not exist for this customer.`);
    return p;
  }

  platform(key: string) {
    const p = AI_PLATFORMS.find((x) => x.key === key);
    if (!p) throw new BadRequestException(`Unknown platform. Use one of: ${AI_PLATFORM_KEYS.join(', ')}.`);
    return p;
  }

  // Everything the Layer 5 page shows: one block per platform with its prompts.
  async view(customerId: string, month: string) {
    const project = await this.monthOf(customerId, month);
    const [rows, states, globalKeys] = await Promise.all([
      this.pr.find({ where: { projectId: project.id }, order: { rank: 'ASC' } }),
      this.pf.find({ where: { projectId: project.id } }),
      this.globalApis.getKeys(),
    ]);
    const platforms = AI_PLATFORMS.map((p) => {
      const st = states.find((s) => s.platform === p.key);
      const records = rows.filter((r) => r.platform === p.key).map((r) => ({ rank: r.rank, prompt: r.prompt, intent: r.intent, promptType: r.promptType, demand: r.demand, source: r.source }));
      const mode = st?.mode || p.defaultMode;
      let status = st?.status || 'idle';
      if (status === 'running' && st?.lastRunAt && Date.now() - new Date(st.lastRunAt).getTime() > STALE_RUN_MS) status = 'failed';
      if (status === 'idle' && records.length) status = records.length >= L5_PER_PLATFORM ? 'complete' : 'partial';
      const keyReady = p.globalKey ? !!globalKeys[p.keyProvider || p.key] : false;
      return { platform: p.key, label: p.label, mode, status, message: st?.message || '', count: records.length, expected: L5_PER_PLATFORM, keyReady, records };
    });
    return {
      month: project.monthCode,
      expected: AI_PLATFORMS.length * L5_PER_PLATFORM,
      total: platforms.reduce((a, p) => a + p.count, 0),
      completePlatforms: platforms.filter((p) => p.count >= L5_PER_PLATFORM).length,
      complete: platforms.every((p) => p.count >= L5_PER_PLATFORM),
      platforms,
    };
  }

  private async state(project: Project, platform: string): Promise<Layer5Platform> {
    const existing = await this.pf.findOne({ where: { projectId: project.id, platform } });
    if (existing) return existing;
    const mode = this.platform(platform).defaultMode;
    return this.pf.create({ customerId: project.customerId, projectId: project.id, platform, mode, status: 'idle', message: null, lastRunAt: null });
  }

  async setMode(customerId: string, month: string, platform: string, mode: string) {
    this.platform(platform);
    if (mode !== 'api' && mode !== 'manual') throw new BadRequestException('mode must be api or manual.');
    const project = await this.monthOf(customerId, month);
    const st = await this.state(project, platform);
    st.mode = mode;
    await this.pf.save(st);
    return this.view(customerId, month);
  }

  private async replaceRows(project: Project, platform: string, rows: PromptRow[], source: string) {
    await this.pr.delete({ projectId: project.id, platform });
    if (rows.length) {
      await this.pr.save(rows.map((r, i) => this.pr.create({ customerId: project.customerId, projectId: project.id, monthIndex: project.monthIndex, platform, rank: i + 1, prompt: r.prompt, intent: r.intent, promptType: r.promptType, demand: r.demand, source })));
    }
  }

  // Keeps the Layer 5 row in the Layer schedule in step with the table: done when all 9 platforms hold 10 prompts.
  async syncLayerStatus(project: Project) {
    const rows = await this.pr.find({ where: { projectId: project.id }, select: ['platform'] });
    const complete = AI_PLATFORMS.every((p) => rows.filter((r) => r.platform === p.key).length >= L5_PER_PLATFORM);
    await this.layers.setByMonth(project.customerId, project.monthIndex, 5, complete ? 'done' : rows.length ? 'in_progress' : 'pending');
    return complete;
  }

  async saveManual(customerId: string, month: string, platform: string, text: string) {
    this.platform(platform);
    const rows = parseManualLines(String(text || ''));
    if (!rows.length) throw new BadRequestException('Add at least one prompt, one per line: prompt | Intent | Prompt Type | Demand.');
    const project = await this.monthOf(customerId, month);
    await this.replaceRows(project, platform, rows, 'manual');
    const st = await this.state(project, platform);
    st.mode = 'manual';
    st.status = rows.length >= L5_PER_PLATFORM ? 'complete' : 'partial';
    st.message = `${rows.length}/${L5_PER_PLATFORM} prompts saved manually.`;
    st.lastRunAt = new Date();
    await this.pf.save(st);
    await this.syncLayerStatus(project);
    return this.view(customerId, month);
  }

  // Bulk import of a whole month's table (all platforms at once). One row per line, tab or | separated:
  // Platform, Rank, Prompt, Intent, Prompt Type, Demand. A header line is ignored. Replaces only the platforms present.
  async importTable(customerId: string, month: string, text: string) {
    const alias: Record<string, string> = {
      chatgpt: 'openai', openai: 'openai', gemini: 'gemini', perplexity: 'perplexity', claude: 'anthropic', anthropic: 'anthropic',
      grok: 'xai', xai: 'xai', deepseek: 'deepseek', copilot: 'copilot', 'meta ai': 'meta', meta: 'meta', 'google ai': 'google_ai', google_ai: 'google_ai',
    };
    const groups = new Map<string, Array<{ rank: number; row: PromptRow }>>();
    const skipped: string[] = [];
    for (const raw of String(text || '').split(/\r?\n/)) {
      const line = raw.trim();
      if (!line) continue;
      const parts = line.split(line.includes('\t') ? '\t' : '|').map((x) => x.trim());
      const key = alias[(parts[0] || '').toLowerCase()];
      if (!key) { if (!/^platform$/i.test(parts[0] || '')) skipped.push(line.slice(0, 60)); continue; }
      const prompt = (parts[2] || '').slice(0, 600);
      if (!prompt) { skipped.push(line.slice(0, 60)); continue; }
      const row: PromptRow = { prompt, intent: pick(parts[3] || '', L5_INTENTS) || 'Informational', promptType: pick(parts[4] || '', L5_TYPES) || 'Research', demand: pick(parts[5] || '', L5_DEMANDS) || 'Medium' };
      groups.set(key, [...(groups.get(key) || []), { rank: Number(parts[1]) || (groups.get(key)?.length || 0) + 1, row }]);
    }
    if (!groups.size) throw new BadRequestException('No rows recognised. Use: Platform, Rank, Prompt, Intent, Prompt Type, Demand (tab or | separated).');
    const project = await this.monthOf(customerId, month);
    const summary: Record<string, number> = {};
    for (const [key, list] of groups) {
      const rows = list.sort((a, b) => a.rank - b.rank).map((x) => x.row).slice(0, L5_PER_PLATFORM);
      await this.replaceRows(project, key, rows, 'import');
      const st = await this.state(project, key);
      st.status = rows.length >= L5_PER_PLATFORM ? 'complete' : 'partial';
      st.message = rows.length + '/' + L5_PER_PLATFORM + ' prompts imported.';
      st.lastRunAt = new Date();
      await this.pf.save(st);
      summary[key] = rows.length;
    }
    const complete = await this.syncLayerStatus(project);
    return { imported: summary, skipped, complete, view: await this.view(customerId, month) };
  }

  private async keysFor(platform: string): Promise<Record<string, string>> {
    const def = this.platform(platform);
    const kp = def.keyProvider || platform;
    const vals = (await this.globalApis.getKeys())[kp];
    if (!vals) throw new BadRequestException(`${def.label} has no key yet. Add and enable ${kp === platform ? def.label : kp === 'openrouter' ? 'OpenRouter' : kp} in Global API Settings.`);
    return vals;
  }

  // Starts a run in the background (an AI call can take a minute); the page polls view().
  async startRun(customerId: string, month: string, platform: string) {
    const def = this.platform(platform);
    const project = await this.monthOf(customerId, month);
    const st = await this.state(project, platform);
    if ((st.mode || def.defaultMode) === 'manual') throw new BadRequestException(`${def.label} is set to Manual - paste its prompts instead, or switch it to API.`);
    if (st.status === 'running' && st.lastRunAt && Date.now() - new Date(st.lastRunAt).getTime() < STALE_RUN_MS) throw new BadRequestException(`${def.label} is already running.`);
    const customer = await this.customers.findOne({ where: { id: customerId } });
    if (!customer) throw new NotFoundException('Customer not found.');
    const vals = await this.keysFor(platform);
    st.status = 'running';
    st.message = 'Asking ' + def.label + '…';
    st.lastRunAt = new Date();
    await this.pf.save(st);
    void this.execute(project, customer, platform, vals).catch((err) => this.log.error(`Layer 5 ${platform}: ${err?.message || err}`));
    return this.view(customerId, month);
  }

  // Keeps two calls to the same provider at least `ms` apart (one at a time per provider, in the order queued).
  private async pace(provider: string, ms = 3000) {
    const wait = (this.lastCall.get(provider) || 0) + ms - Date.now();
    if (wait > 0) await sleep(wait);
    this.lastCall.set(provider, Date.now());
  }

  async execute(project: Project, customer: Customer, platform: string, vals: Record<string, string>) {
    const def = this.platform(platform);
    const st = await this.state(project, platform);
    try {
      await this.pace(def.keyProvider || platform);
      const prompt = layer5Prompt(customer, platform);
      const reply = platform === 'google_ai' ? await askGoogleAi(vals.apiKey, prompt) : await askPlatform(platform, vals, prompt);
      const rows = parseLayer5Reply(reply);
      if (rows.length) await this.replaceRows(project, platform, rows, 'api');
      st.status = rows.length >= L5_PER_PLATFORM ? 'complete' : rows.length ? 'partial' : 'failed';
      st.message = rows.length
        ? rows.length >= L5_PER_PLATFORM ? `${rows.length}/${L5_PER_PLATFORM} valid prompts stored.` : `${def.label} returned ${rows.length}/${L5_PER_PLATFORM} valid prompts.`
        : `${def.label} returned no valid prompt records (needs a JSON array with rank, prompt, intent, prompt_type, demand). Existing prompts were kept.`;
    } catch (err) {
      st.status = 'failed';
      st.message = (err instanceof Error ? err.message : 'Run failed').slice(0, 380);
    }
    st.lastRunAt = new Date();
    await this.pf.save(st);
    await this.syncLayerStatus(project);
  }

  // ---- Automation: the set date (Day 5 of the Month Cycle) ----------------------------------------
  // Platform-major, one call at a time, same rules as Layer 4. Skips Manual platforms, platforms already attempted
  // today and platforms already holding 10 prompts.
  async runDay(monthRows: Array<{ customerId: string; monthIndex: number }>, force = false): Promise<string> {
    const today = dateInTz(new Date());
    const targets: Array<{ project: Project; customer: Customer }> = [];
    for (const m of monthRows) {
      const project = await this.projects.findOne({ where: { customerId: m.customerId, monthIndex: m.monthIndex } });
      const customer = await this.customers.findOne({ where: { id: m.customerId } });
      if (project && customer) targets.push({ project, customer });
    }
    const keys = await this.globalApis.getKeys();
    let calls = 0;
    for (const def of AI_PLATFORMS) {
      const vals = keys[def.keyProvider || def.key];
      if (def.defaultMode === 'manual' && !def.keyProvider) continue;
      for (const { project, customer } of targets) {
        const st = await this.state(project, def.key);
        if ((st.mode || def.defaultMode) === 'manual') continue;
        if (!vals) {
          if (st.lastRunAt && dateInTz(st.lastRunAt) === today) continue;
          st.status = 'failed'; st.message = `${def.label} has no key in Global API Settings.`; st.lastRunAt = new Date();
          await this.pf.save(st);
          continue;
        }
        if (!force && st.lastRunAt && dateInTz(st.lastRunAt) === today && st.status !== 'idle') continue;
        const have = await this.pr.count({ where: { projectId: project.id, platform: def.key } });
        if (!force && have >= L5_PER_PLATFORM) continue;
        st.status = 'running'; st.message = 'Scheduled run…'; st.lastRunAt = new Date();
        await this.pf.save(st);
        await this.execute(project, customer, def.key, vals);
        calls++;
      }
    }
    for (const { project } of targets) await this.syncLayerStatus(project);
    return `${calls} platform call(s) for ${targets.length} customer month(s)`;
  }

  // ---- Customer panel: the finished table only -----------------------------------------------------
  // Returns the full 9-platform table once every platform holds its 10 prompts; nothing before that.
  async customerTable(customerId: string, month?: string) {
    let project: Project | null = null;
    if (month) project = await this.monthOf(customerId, month);
    else {
      const today = todayInTz();
      const all = await this.projects.find({ where: { customerId }, order: { monthIndex: 'ASC' } });
      project = all.find((p) => p.monthStartDate && p.monthEndDate && p.monthStartDate <= today && today <= p.monthEndDate) || all[0] || null;
    }
    const expected = AI_PLATFORMS.length * L5_PER_PLATFORM;
    if (!project) return { layer: 5, complete: false, month: null, total: 0, expected, html: '', platforms: [] };
    const rows = await this.pr.find({ where: { projectId: project.id }, order: { rank: 'ASC' } });
    const platforms = AI_PLATFORMS.map((p) => ({ platform: p.key, label: p.label, records: rows.filter((r) => r.platform === p.key) }));
    const complete = platforms.every((p) => p.records.length >= L5_PER_PLATFORM);
    if (!complete) return { layer: 5, complete: false, month: project.monthCode, total: rows.length, expected, html: '', platforms: [] };
    const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c] as string));
    const shown = platforms.map((p) => ({
      platform: p.platform,
      label: p.label,
      records: p.records.map((r) => ({ rank: r.rank, prompt: r.prompt, intent: r.intent, promptType: r.promptType, demand: r.demand })),
    }));
    const body = shown
      .flatMap((p) => p.records.map((r) => `<tr><td>${esc(p.label)}</td><td>${r.rank}</td><td>${esc(r.prompt)}</td><td>${esc(r.intent)}</td><td>${esc(r.promptType)}</td><td>${esc(r.demand)}</td></tr>`))
      .join('');
    const html = `<table class="kp21-l5"><thead><tr><th>AI platform</th><th>#</th><th>AI search prompt</th><th>Intent</th><th>Prompt type</th><th>Demand</th></tr></thead><tbody>${body}</tbody></table>`;
    return { layer: 5, complete: true, month: project.monthCode, total: rows.length, expected, html, platforms: shown };
  }

  async removeByCustomer(customerId: string) {
    await this.pr.delete({ customerId });
    await this.pf.delete({ customerId });
  }
}
