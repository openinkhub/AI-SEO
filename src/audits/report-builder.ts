// Builds the "Branded report" the user's spec calls for: "create a Branded
// report ... report will be generated and view on customer panel." The
// customer panel itself isn't built yet (not yet started per the migration
// plan), so for now this HTML is served directly by GET
// /api/v1/customers/:customerId/audits/:runId/report and is meant to be
// embedded/iframed once that panel exists.
export function buildBrandedReportHtml(
  run: AuditRun,
  tasks: AuditTask[],
  customerName: string,
  evidence: AuditEvidence[] = [],
): string {
  const byLayer = groupByLayer(tasks);
  const automated = tasks.filter((t) => t.isAutomated);
  const withFindings = tasks.filter((t) => t.status === 'completed' && t.finding);

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>Openink Hub — SEO Audit — ${escapeHtml(customerName)}</title>
${styleBlock()}
</head>
<body>
  <header class="brand-header">
    <div class="brand-mark">Openink Hub</div>
    <h1>SEO Audit</h1>
    <p class="meta">${escapeHtml(customerName)} &middot; ${escapeHtml(run.website ?? '')} &middot; ${formatDate(run.completedAt ?? run.createdAt)}</p>
  </header>
  ${summaryBlock(run, tasks, automated, withFindings)}
  ${renderEvidenceHtml(evidence, 'admin', { side: 'internal', heading: 'Internal audit - research sources (your website)' })}
  ${renderEvidenceHtml(evidence, 'admin', { side: 'external', heading: 'External audit - research sources (search engines, competitors, authority)' })}
  ${taskMatrixBlock(tasks)}
  ${layerSectionsBlock(byLayer, collectMetrics(evidence), new Set(tasks.filter((t) => TASK_SOURCE[`${t.plugin}:${t.skill}`] === 'backlinks').flatMap((t) => t.layerNumbers)))}
  ${appendixBlock(tasks)}
  <footer class="brand-footer">Generated by the Openink Hub AI-SEO Engine &middot; Layer 3 — SEO Audit</footer>
</body>
</html>`;
}

// Customer-facing report (shown in Layer 3 of the customer panel). The full report above - the
// 140-skill task list, per-layer findings and "pending data source" rows - is admin-only.
// This one lists only the checks that actually ran against the customer's site, each finding once.
export function buildCustomerReportHtml(
  run: AuditRun,
  tasks: AuditTask[],
  customerName: string,
  evidence: AuditEvidence[] = [],
  pages: ReportPage[] = [],
): string {
  const bodyHtml = customerReportBody(run, tasks, evidence, pages);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>Openink Hub — SEO Audit — ${escapeHtml(customerName)}</title>
${styleBlock()}
</head>
<body>
  <header class="brand-header">
    <div class="brand-mark">Openink Hub</div>
    <h1>SEO Audit</h1>
    <p class="meta">${escapeHtml(customerName)} &middot; ${escapeHtml(run.website ?? '')} &middot; ${formatDate(run.completedAt ?? run.createdAt)}</p>
  </header>
  ${bodyHtml}
  <footer class="brand-footer">Prepared by Openink Hub &middot; SEO Audit</footer>
</body>
</html>`;
}

// Inner sections of the customer report (stats, findings, approved tool evidence) - reused by the compiled package.
export interface ReportPage {
  pageName: string | null;
  pageUrl: string;
  h1Keyword: string | null;
  metaTitle: string | null;
  metaDescription: string | null;
  aliasName?: string | null;
  imageUrl?: string | null;
  imageName?: string | null;
}

// "Page mapping": alias name, H1 keyword and the branded image mapped to each page.
function pageMappingBlock(pages: ReportPage[]): string {
  if (!pages.length) return '';
  const cell = (v: string | null | undefined) => (v ? escapeHtml(v) : '—');
  const img = (p: ReportPage) =>
    p.imageUrl
      ? `<img src="${escapeHtml(p.imageUrl)}" alt="${escapeHtml(p.imageName ?? '')}" style="max-width:96px;max-height:64px;border-radius:4px;vertical-align:middle" /> <span class="empty">${escapeHtml(p.imageName ?? '')}</span>`
      : '<span class="empty">No image mapped</span>';
  const rows = pages
    .map((p) => `<tr><td>${cell(p.pageName)}<br><a href="${escapeHtml(p.pageUrl)}">${escapeHtml(p.pageUrl)}</a></td><td>${cell(p.aliasName)}</td><td>${cell(p.h1Keyword)}</td><td>${img(p)}</td></tr>`)
    .join('');
  const mapped = pages.filter((p) => p.imageUrl).length;
  return `<section class="layers"><h2>Page mapping (${mapped} of ${pages.length} pages have an image)</h2><p class="empty">The alias name, H1 keyword and branded image used for each page.</p><table><thead><tr><th>Page</th><th>Alias name</th><th>H1 keyword</th><th>Image</th></tr></thead><tbody>${rows}</tbody></table></section>`;
}

// "Website pages" list view: one row per page of the customer's site.
function pagesBlock(pages: ReportPage[]): string {
  if (!pages.length) return '';
  const cell = (v: string | null) => (v ? escapeHtml(v) : '—');
  const rows = pages
    .map((p) => `<tr><td>${cell(p.pageName)}</td><td><a href="${escapeHtml(p.pageUrl)}">${escapeHtml(p.pageUrl)}</a></td><td>${cell(p.h1Keyword)}</td><td>${cell(p.metaTitle)}</td><td>${cell(p.metaDescription)}</td></tr>`)
    .join('');
  return `<section class="layers"><h2>Website pages (${pages.length})</h2><p class="empty">Every page we found on your site, with its main heading (H1 keyword), meta title and meta description.</p><table><thead><tr><th>Page</th><th>URL</th><th>H1 keyword</th><th>Meta title</th><th>Meta description</th></tr></thead><tbody>${rows}</tbody></table></section>`;
}

export function customerReportBody(run: AuditRun, tasks: AuditTask[], evidence: AuditEvidence[] = [], pages: ReportPage[] = []): string {
  // Every completed task gets its own row (each names its task and research source), no hiding of look-alike findings.
  const items = tasks.filter((t) => t.isAutomated && t.finding);
  const real = items;
  const notApplicable = tasks.filter((t) => TASK_SOURCE[`${t.plugin}:${t.skill}`] === 'na').length;
  const inProgress = Math.max(tasks.length - real.length - notApplicable, 0);
  const stat = (label: string, value: string | number) =>
    `<div class="stat"><div class="stat-value">${value}</div><div class="stat-label">${escapeHtml(label)}</div></div>`;
  const taskTable = (list: AuditTask[], note: string): string => {
    if (!list.length) return '<p class="empty">No completed tasks in this part yet.</p>';
    const rows = list
      .map((t) => `<tr><td>${escapeHtml(taskName(t))}</td><td>${escapeHtml(t.dataSource ?? '')}</td><td>${escapeHtml(t.finding ?? '')}</td><td>${escapeHtml(t.suggestion ?? '—')}</td></tr>`)
      .join('');
    return `<p class="empty">${escapeHtml(note)}</p><table><thead><tr><th>Task</th><th>Research source</th><th>What we found</th><th>What we suggest</th></tr></thead><tbody>${rows}</tbody></table>`;
  };
  const sideOf = (t: AuditTask) => SOURCE_SIDE[TASK_SOURCE[`${t.plugin}:${t.skill}`] ?? 'ai'] ?? 'internal';
  const internal = items.filter((t) => sideOf(t) !== 'external');
  const external = items.filter((t) => sideOf(t) === 'external');
  const part = (title: string, intro: string, ev: string, list: AuditTask[]) =>
    `<section class="layers"><h2>${escapeHtml(title)}</h2><p class="empty">${escapeHtml(intro)}</p></section>${ev}<section class="layers"><h3>${escapeHtml(title)} - task results</h3>${taskTable(list, 'Each result comes from the research above.')}</section>`;
  const internalEv = renderEvidenceHtml(evidence, 'customer', { side: 'internal', heading: 'Research sources - your website' });
  const externalEv = renderEvidenceHtml(evidence, 'customer', { side: 'external', heading: 'Research sources - search engines, competitors and authority' });
  const body = !items.length
    ? `<section class="layers"><h2>SEO task results</h2><p class="empty">${escapeHtml(run.failureReason ?? 'No findings were produced for this audit.')}</p></section>`
    : part('Internal audit', 'What we checked on your own website: pages, technical set-up, speed, on-page elements and content.', internalEv, internal) +
      part('External audit', 'What we checked outside your website: Google results, keywords, competitors, authority, backlinks and AI search visibility.', externalEv, external);
  return `<section class="summary">
    ${stat('Tasks completed', `${real.length} of ${tasks.length}`)}
    ${stat('Internal audit tasks', internal.length)}
    ${stat('External audit tasks', external.length)}
    ${stat('Not applicable to an SEO audit', notApplicable)}
    ${stat('Not completed yet', inProgress)}
  </section>
  ${pagesBlock(pages)}
  ${pageMappingBlock(pages)}
  ${body}`;
}

function taskName(t: AuditTask): string {
  return t.skill.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase());
}

// Admin: all 140 tasks as their own section, grouped by research source (kept apart from the source cards).
function taskMatrixBlock(tasks: AuditTask[]): string {
  const order = Object.keys(SOURCE_LABEL);
  const groups = new Map<string, AuditTask[]>();
  for (const t of tasks) {
    const k = TASK_SOURCE[`${t.plugin}:${t.skill}`] ?? 'ai';
    groups.set(k, [...(groups.get(k) ?? []), t]);
  }
  const sections = order
    .filter((k) => groups.has(k))
    .map((k) => {
      const list = groups.get(k) as AuditTask[];
      const done = list.filter((t) => t.isAutomated).length;
      const rows = list
        .map((t) => `<tr><td>${escapeHtml(t.plugin)}:${escapeHtml(t.skill)}</td><td>${t.isAutomated ? 'Done' : 'Pending'}</td><td>${escapeHtml(truncate(t.finding ?? '', 260))}</td><td>${escapeHtml(truncate(t.suggestion ?? '', 200))}</td></tr>`)
        .join('');
      return `<div class="layer-card"><h3>${escapeHtml(SOURCE_SIDE[k as keyof typeof SOURCE_LABEL] === 'external' ? 'External' : SOURCE_SIDE[k as keyof typeof SOURCE_LABEL] === 'internal' ? 'Internal' : 'N/A')} audit · ${escapeHtml(SOURCE_LABEL[k as keyof typeof SOURCE_LABEL])} <span class="muted">(${done}/${list.length} done)</span></h3><table><thead><tr><th>Task</th><th>Status</th><th>Finding</th><th>Suggestion</th></tr></thead><tbody>${rows}</tbody></table></div>`;
    })
    .join('');
  return `<section class="layers"><h2>${tasks.length}-Task Matrix (by research source)</h2>${sections}</section>`;
}

function groupByLayer(tasks: AuditTask[]): Map<number, AuditTask[]> {
  const map = new Map<number, AuditTask[]>();
  for (const task of tasks) {
    if (!task.finding) continue;
    for (const layer of task.layerNumbers) {
      if (!map.has(layer)) map.set(layer, []);
      map.get(layer)!.push(task);
    }
  }
  return new Map([...map.entries()].sort((a, b) => a[0] - b[0]));
}

function summaryBlock(run: AuditRun, tasks: AuditTask[], automated: AuditTask[], withFindings: AuditTask[]): string {
  const stat = (label: string, value: string | number) =>
    `<div class="stat"><div class="stat-value">${value}</div><div class="stat-label">${escapeHtml(label)}</div></div>`;
  return `<section class="summary">
    ${stat('Skills assessed', tasks.length)}
    ${stat('Live technical checks', automated.length)}
    ${stat('Findings generated', withFindings.length)}
    ${stat('Layers mapped', new Set(tasks.flatMap((t) => t.layerNumbers)).size)}
    ${stat('Status', run.status)}
  </section>`;
}

// compare = the source-by-source authority / traffic / backlinks table; compareLayers = the layers whose backlink
// tasks it belongs to. Admin only: the customer report shows each tool's own data as it is.
function layerSectionsBlock(byLayer: Map<number, AuditTask[]>, metricRows: MetricRow[] = [], compareLayers: Set<number> = new Set()): string {
  // Shown once, under the first layer that carries the backlink tasks, and says which layers it applies to.
  const layersList = [...compareLayers].sort((a, b) => a - b);
  const compare = renderMetricCompare(metricRows, `Authority, traffic and backlinks - all sources compared${layersList.length ? ` (applies to Layers ${layersList.join(', ')})` : ''}`);
  const firstLayer = [...byLayer.keys()].find((l) => compareLayers.has(l));
  if (byLayer.size === 0) {
    return `<section class="layers"><h2>Findings by Layer</h2><p class="empty">No layer-mapped findings yet.</p>${compare}</section>`;
  }
  const sections = [...byLayer.entries()]
    .map(
      ([layer, tasks]) => `<div class="layer-card">
        <h3>Layer ${layer}</h3>
        <ul>
          ${tasks.map((t) => `<li><strong>${escapeHtml(t.skill)}</strong> (${escapeHtml(t.plugin)}): ${escapeHtml(t.finding ?? '')}${t.suggestion ? ` <em>&mdash; ${escapeHtml(t.suggestion)}</em>` : ''}</li>`).join('')}
        </ul>
        ${compare && layer === firstLayer ? compare : ''}
      </div>`,
    )
    .join('');
  // No layer carries the backlink tasks yet (no findings): still show the comparison once.
  if (compare && firstLayer === undefined) return `<section class="layers"><h2>Findings by Layer</h2>${sections}${compare}</section>`;
  return `<section class="layers"><h2>Findings by Layer</h2>${sections}</section>`;
}

function appendixBlock(tasks: AuditTask[]): string {
  const rows = tasks
    .map(
      (t) => `<tr>
        <td>${escapeHtml(t.group)}</td>
        <td>${escapeHtml(t.plugin)}:${escapeHtml(t.skill)}</td>
        <td>${escapeHtml(t.implementationType)}</td>
        <td>${escapeHtml(t.actionType)}</td>
        <td>${escapeHtml(t.layerNumbers.join(', ') || '—')}</td>
        <td>${escapeHtml(t.status)}${t.isAutomated ? '' : ' (pending data source)'}</td>
        <td>${escapeHtml(truncate(t.finding ?? '', 140))}</td>
      </tr>`,
    )
    .join('');
  return `<section class="appendix">
    <h2>All ${tasks.length} Skills — Task Detail</h2>
    <table>
      <thead><tr><th>Group</th><th>Skill</th><th>Type</th><th>Action</th><th>Layer(s)</th><th>Status</th><th>Finding</th></tr></thead>
      <tbody>${rows}</tbody>
    </table>
  </section>`;
}

